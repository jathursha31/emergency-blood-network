-- V2: refresh tokens for longer sessions with short-lived access tokens.
-- Only a SHA-256 hash of each token is stored. Tokens are rotated on every use; all tokens issued from
-- one login share a "family", so reuse of an old (rotated) token revokes the whole family.

create table refresh_tokens (
    id             bigint generated by default as identity primary key,
    account_id     bigint       not null,
    token_hash     varchar(64)  not null,
    family         varchar(36)  not null,
    created_at     timestamp(6) not null,
    expires_at     timestamp(6) not null,
    revoked_at     timestamp(6),
    revoked_reason varchar(20),
    user_agent     varchar(200),
    constraint uk_refresh_token_hash unique (token_hash),
    constraint fk_refresh_account foreign key (account_id) references user_accounts (id)
);

create index idx_refresh_account on refresh_tokens (account_id);
create index idx_refresh_family on refresh_tokens (family);
