-- V1: initial schema of the Blood Donor Emergency Network.
-- Matches the JPA entities (Hibernate runs with ddl-auto=validate and fails at startup if they drift).
-- Plain SQL that runs on PostgreSQL and on H2 (PostgreSQL mode, used by the tests).
-- Never edit a migration that has been applied; add V2__..., V3__... instead.

-- ---------------------------------------------------------------- hospitals & donors

create table hospitals (
    id          bigint generated by default as identity primary key,
    name        varchar(150) not null,
    phone       varchar(15)  not null,
    address     varchar(250),
    city        varchar(60),
    latitude    float(53)    not null,
    longitude   float(53)    not null
);

create table donors (
    id                 bigint generated by default as identity primary key,
    full_name          varchar(100) not null,
    phone              varchar(15)  not null,
    email              varchar(120),
    date_of_birth      date         not null,
    blood_group        varchar(10)  not null,
    latitude           float(53)    not null,
    longitude          float(53)    not null,
    city               varchar(60),
    last_donation_date date,
    available          boolean      not null,
    registered_at      timestamp(6) not null,
    constraint uk_donor_phone unique (phone),
    constraint ck_donor_blood_group check (blood_group in ('O_NEG','O_POS','A_NEG','A_POS','B_NEG','B_POS','AB_NEG','AB_POS'))
);

create index idx_donor_group_location on donors (blood_group, latitude, longitude);

create table user_accounts (
    id            bigint generated by default as identity primary key,
    username      varchar(60)  not null,
    password_hash varchar(100) not null,
    role          varchar(10)  not null,
    donor_id      bigint,
    hospital_id   bigint,
    enabled       boolean      not null,
    created_at    timestamp(6) not null,
    constraint uk_account_username unique (username),
    constraint uk_account_donor unique (donor_id),
    constraint ck_account_role check (role in ('ADMIN','HOSPITAL','DONOR')),
    constraint fk_account_donor foreign key (donor_id) references donors (id),
    constraint fk_account_hospital foreign key (hospital_id) references hospitals (id)
);

-- ---------------------------------------------------------------- emergency requests

create table blood_requests (
    id               bigint generated by default as identity primary key,
    hospital_id      bigint       not null,
    patient_name     varchar(100) not null,
    blood_group      varchar(10)  not null,
    units_needed     integer      not null,
    urgency          varchar(10)  not null,
    status           varchar(10)  not null,
    search_radius_km float(53)    not null,
    needed_by        timestamp(6) not null,
    created_at       timestamp(6) not null,
    last_search_at   timestamp(6),
    closed_at        timestamp(6),
    restock          boolean      default false not null,
    constraint ck_request_blood_group check (blood_group in ('O_NEG','O_POS','A_NEG','A_POS','B_NEG','B_POS','AB_NEG','AB_POS')),
    constraint ck_request_urgency check (urgency in ('CRITICAL','HIGH','NORMAL')),
    constraint ck_request_status check (status in ('OPEN','MATCHED','FULFILLED','CANCELLED','EXPIRED')),
    constraint fk_request_hospital foreign key (hospital_id) references hospitals (id)
);

create index idx_request_status on blood_requests (status);

create table donor_responses (
    id           bigint generated by default as identity primary key,
    request_id   bigint       not null,
    donor_id     bigint       not null,
    status       varchar(10)  not null,
    distance_km  float(53)    not null,
    notified_at  timestamp(6) not null,
    responded_at timestamp(6),
    donated_at   timestamp(6),
    constraint uk_response_request_donor unique (request_id, donor_id),
    constraint ck_response_status check (status in ('NOTIFIED','ACCEPTED','DECLINED','DONATED')),
    constraint fk_response_request foreign key (request_id) references blood_requests (id),
    constraint fk_response_donor foreign key (donor_id) references donors (id)
);

-- ---------------------------------------------------------------- blood bank

create table blood_stock (
    id           bigint generated by default as identity primary key,
    hospital_id  bigint       not null,
    blood_group  varchar(10)  not null,
    units        integer      not null,
    min_units    integer      not null,
    auto_request boolean      not null,
    updated_at   timestamp(6) not null,
    constraint uk_stock_hospital_group unique (hospital_id, blood_group),
    constraint ck_stock_blood_group check (blood_group in ('O_NEG','O_POS','A_NEG','A_POS','B_NEG','B_POS','AB_NEG','AB_POS')),
    constraint fk_stock_hospital foreign key (hospital_id) references hospitals (id)
);

-- ---------------------------------------------------------------- donation camps

create table donation_camps (
    id                bigint generated by default as identity primary key,
    hospital_id       bigint       not null,
    name              varchar(150) not null,
    address           varchar(250),
    city              varchar(60),
    latitude          float(53)    not null,
    longitude         float(53)    not null,
    camp_date         date         not null,
    start_time        time(0)      not null,
    end_time          time(0)      not null,
    slot_minutes      integer      not null,
    capacity_per_slot integer      not null,
    status            varchar(10)  not null,
    created_at        timestamp(6) not null,
    constraint ck_camp_status check (status in ('ACTIVE','CANCELLED')),
    constraint fk_camp_hospital foreign key (hospital_id) references hospitals (id)
);

create index idx_camp_date on donation_camps (camp_date);

create table camp_bookings (
    id            bigint generated by default as identity primary key,
    camp_id       bigint       not null,
    donor_id      bigint       not null,
    slot_time     time(0)      not null,
    code          varchar(12)  not null,
    status        varchar(10)  not null,
    booked_at     timestamp(6) not null,
    checked_in_at timestamp(6),
    constraint uk_booking_code unique (code),
    constraint ck_booking_status check (status in ('BOOKED','CANCELLED','ATTENDED')),
    constraint fk_booking_camp foreign key (camp_id) references donation_camps (id),
    constraint fk_booking_donor foreign key (donor_id) references donors (id)
);

create index idx_booking_camp_slot on camp_bookings (camp_id, slot_time);

-- ---------------------------------------------------------------- one-time codes

create table otp_codes (
    id         bigint generated by default as identity primary key,
    phone      varchar(15)  not null,
    purpose    varchar(10)  not null,
    code_hash  varchar(100) not null,
    expires_at timestamp(6) not null,
    attempts   integer      not null,
    used       boolean      not null,
    created_at timestamp(6) not null,
    constraint ck_otp_purpose check (purpose in ('LOGIN','REGISTER'))
);

create index idx_otp_phone_purpose on otp_codes (phone, purpose, created_at);
