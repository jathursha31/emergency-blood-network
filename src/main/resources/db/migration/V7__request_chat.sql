-- Messages between a hospital and a donor who accepted one of its blood requests.
-- One conversation per donor response (request + donor).
create table chat_messages (
    id          bigint generated by default as identity primary key,
    response_id bigint       not null,
    sender      varchar(10)  not null,
    sender_name varchar(120) not null,
    body        varchar(1000) not null,
    created_at  timestamp(6) not null,
    read_at     timestamp(6),
    constraint fk_chat_response foreign key (response_id) references donor_responses (id),
    constraint ck_chat_sender check (sender in ('HOSPITAL', 'DONOR'))
);
create index idx_chat_response on chat_messages (response_id, created_at);
