-- V6: Web Push notifications.

-- Small key/value store for generated settings, e.g. the VAPID key pair (made once, kept forever:
-- browser subscriptions are tied to the public key).
create table app_settings (
    setting_key   varchar(60)   primary key,
    setting_value varchar(2000) not null
);

-- One row per browser/device that allowed notifications.
create table push_subscriptions (
    id              bigint generated by default as identity primary key,
    account_id      bigint        not null,
    endpoint        varchar(1000) not null,
    p256dh          varchar(200)  not null,   -- browser's public key (base64url)
    auth            varchar(100)  not null,   -- browser's auth secret (base64url)
    user_agent      varchar(200),
    created_at      timestamp(6)  not null,
    last_success_at timestamp(6),
    failures        integer       default 0 not null,
    constraint uk_push_endpoint unique (endpoint),
    constraint fk_push_account foreign key (account_id) references user_accounts (id)
);

create index idx_push_account on push_subscriptions (account_id);
