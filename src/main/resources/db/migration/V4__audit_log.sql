-- V4: last successful login per account, and an append-only audit log of security-relevant events.

alter table user_accounts add column last_login_at timestamp(6);

create table audit_events (
    id         bigint generated by default as identity primary key,
    at         timestamp(6) not null,
    actor      varchar(60),            -- who did it (null = anonymous, e.g. a failed login)
    action     varchar(30)  not null,  -- LOGIN, LOGIN_FAILED, LOGOUT, ACCOUNT_DISABLED, ...
    target     varchar(60),            -- account it was done to
    details    varchar(300),
    ip         varchar(45)
);

create index idx_audit_at on audit_events (at);
create index idx_audit_target on audit_events (target);
create index idx_audit_actor on audit_events (actor);
